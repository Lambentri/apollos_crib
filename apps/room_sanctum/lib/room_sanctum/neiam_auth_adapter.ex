defmodule RoomSanctum.NeiamAuthAdapter do
  @moduledoc """
  Hands neiam_auth (OIDC) logins to the app's own accounts code.
  Generated by `mix neiam_auth.install --flavour gen_auth_17`.
  """

  @behaviour NeiamAuth.Adapter

  alias RoomSanctum.Accounts
  alias RoomSanctum.Accounts.User
  alias RoomSanctum.Repo

  @impl true
  def get_user_by_email(email), do: Accounts.get_user_by_email(email)

  @impl true
  def log_in(conn, user) do
    RoomSanctumWeb.UserAuth.log_in_user(conn, user, %{"remember_me" => "true"})
  end

  @impl true
  def current_user(conn) do
    conn.assigns[:current_user]
  end

  # PROVISION=auto only. A passwordless, confirmed user: hashed_password is
  # nullable since 20261115214900, and User.valid_password?/2 already refuses
  # a nil hash. confirmed_at is a :naive_datetime here (gen.auth 1.7).
  @impl true
  def register_sso_user(%NeiamAuth.Claims{email: email}) when is_binary(email) do
    %User{}
    |> Ecto.Changeset.change(email: email, confirmed_at: NaiveDateTime.utc_now(:second))
    |> Ecto.Changeset.unique_constraint(:email)
    |> Repo.insert()
  end

  def register_sso_user(_claims), do: {:error, :no_email}

  # Refuse rows that must never be signed in to by SSO. RoomSanctum has no
  # guest kind (the kiosk pages are public and need no user), so every
  # account can be linked.
  @impl true
  def linkable?(%User{}), do: true

  # Map IdP groups to role flags. Called on every login, only for
  # providers with GROUPS_CLAIM. RoomSanctum has no role columns: admins come
  # from CRIB_ADMIN_EMAILS (Accounts.admin?/1), which SSO leaves alone. The
  # groups are still recorded on the identity row.
  @impl true
  def apply_groups(user, _groups), do: {:ok, user}

  @impl true
  def login_path, do: "/users/log_in"

  @impl true
  def settings_path, do: "/users/settings"
end
